// Builds 3d/data/world.js, the land outline for the world map, from Natural Earth's 1:110m land
// (public domain, naturalearthdata.com) as packaged by world-atlas 2.0.2 (TopoJSON):
//   curl -o land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json
//   node scripts/world-map.mjs land-110m.json 3d/data/world.js
import { readFileSync, writeFileSync } from 'node:fs';

const [, , inFile, outFile] = process.argv;
if (!inFile || !outFile) { console.error('usage: node scripts/world-map.mjs <land-110m.json> <out.js>'); process.exit(1); }
const topo = JSON.parse(readFileSync(inFile, 'utf8'));
const { scale, translate } = topo.transform;
// decode the delta-encoded, quantised arcs into [lon, lat] points
const arcs = topo.arcs.map(arc => { let x = 0, y = 0; return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * scale[0] + translate[0], y * scale[1] + translate[1]]; }); });
const ring = idx => { const pts = []; for (const i of idx) { const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i]; pts.push(...(pts.length ? a.slice(1) : a)); } return pts; };
const geoms = topo.objects.land.geometries || [topo.objects.land];
const polys = [];
for (const g of geoms) {
  const list = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
  for (const p of list) { const outer = ring(p[0]); if (outer.length > 3) polys.push(outer.flatMap(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10])); }
}
writeFileSync(outFile, `// Land outline for the world map: Natural Earth 1:110m (public domain), via world-atlas 2.0.2. Generated by scripts/world-map.mjs.
window.TU95_WORLD = ${JSON.stringify(polys)};
`);
console.log(`✓ ${outFile}: ${polys.length} land polygons`);
